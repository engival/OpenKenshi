#!/usr/bin/env python3
"""ctest labels from the validity audit (kenshi-k16.15.26).

cpp/tests/validity/*.tsv is the one home of the classification (columns: file, test, assertion, class, source, note). Nothing
else is hand-kept: labels, the CI report grouping and this check are generated from it. Change a class = edit one tsv row; the labels
follow at the next configure. Test column "-" = the file is no ctest (a tool, a shared helper); its rows are documentation only.

A test's class is its strictest check: golden (any grounded row) > pin > infra. Extra labels: unverified (any unverified row),
wrong (any wrong row). A test with no rows is 'unclassified'.

  validity_labels.py --out F.cmake          write the set_property lines (CMake runs this at configure)
  validity_labels.py --check --names F.txt  fail on a row naming a ctest that does not exist, or on a ctest with no rows that
                                            is not in cpp/tests/validity/unclassified.txt (the allowlist only shrinks)
                    [--absent F.txt]        ctests this platform does not build (the ASan twins on MinGW): a row naming one is
                                            not a missing ctest (kenshi-k16.15.38)
                    [--base REF]            also warn (exit status unaffected) about a test file changed since REF with no row of it
                                            touched in the same range
"""
import argparse, glob, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
VALIDITY = os.path.join(HERE, "..", "cpp", "tests", "validity")
CLASSES = ("grounded", "pin", "infra", "unverified", "wrong")
CLASS_LABEL = {"grounded": "golden", "pin": "pin", "infra": "infra"}


def rows():
	"""(tsv basename, file, test, class) for every data row."""
	for path in sorted(glob.glob(os.path.join(VALIDITY, "*.tsv"))):
		with open(path, encoding="utf-8") as fh:
			for n, line in enumerate(fh, 1):
				if n == 1 or not line.strip():
					continue
				c = line.rstrip("\n").split("\t")
				if len(c) < 4 or c[3] not in CLASSES:
					sys.exit("%s:%d: bad row (need file, test, assertion, class in %s)" % (path, n, "/".join(CLASSES)))
				yield os.path.basename(path), c[0], c[1], c[3]


def labels_by_test():
	seen = {}
	for _, _, test, cls in rows():
		if test != "-":
			seen.setdefault(test, set()).add(cls)
	out = {}
	for test, classes in seen.items():
		labels = [CLASS_LABEL[c] for c in ("grounded", "pin", "infra") if c in classes][:1]
		labels += [c for c in ("unverified", "wrong") if c in classes]
		out[test] = labels
	return out


def read_list(path):
	with open(path, encoding="utf-8") as fh:
		return [l.split("#")[0].strip() for l in fh if l.split("#")[0].strip()]


def write_cmake(path):
	labels = labels_by_test()
	lines = ["# Generated by tools/validity_labels.py from cpp/tests/validity/*.tsv. Do not edit.\n",
		"set(KSIM_VALIDITY_CLASSIFIED %s)\n" % " ".join(sorted(labels))]
	for test in sorted(labels):
		lines.append("if(TEST %s)\n\tset_property(TEST %s APPEND PROPERTY LABELS %s)\nendif()\n" % (test, test, " ".join(labels[test])))
	lines.append("get_property(validity_all_tests DIRECTORY PROPERTY TESTS)\n"
		"foreach(validity_test IN LISTS validity_all_tests)\n"
		"\tif(NOT validity_test IN_LIST KSIM_VALIDITY_CLASSIFIED)\n"
		"\t\tset_property(TEST ${validity_test} APPEND PROPERTY LABELS unclassified)\n"
		"\tendif()\n"
		"endforeach()\n")
	new = "".join(lines)
	try:
		if open(path, encoding="utf-8").read() == new:
			return  # keep the mtime: no reconfigure loop
	except OSError:
		pass
	with open(path, "w", encoding="utf-8") as fh:
		fh.write(new)


def git(*args):
	# from the top: the pathspecs (cpp/tests/...) are relative to the cwd, and from tools/ they matched nothing (kenshi-fut5)
	return subprocess.run(["git", "-C", os.path.join(HERE, "..")] + list(args), capture_output=True, text=True).stdout


def stale_rows_warnings(base):
	"""Test sources changed since base whose rows no commit in the range touched."""
	files = {}
	for _, f, t, _ in rows():
		files.setdefault(f, set())
	changed = [p for p in git("diff", "--name-only", base + "...HEAD", "--", "cpp/tests/*.cpp", "cpp/tests/*.hpp").split()]
	touched = set()
	for l in git("diff", "-U0", base + "...HEAD", "--", "cpp/tests/validity/*.tsv").splitlines():
		if l[:1] in "+-" and l[:3] not in ("+++", "---"):
			touched.add(l[1:].split("\t")[0])
	return ["WARN: %s changed without its validity rows touched (cpp/tests/validity/*.tsv; update them if a check changed)" % os.path.basename(p)
		for p in changed if os.path.basename(p) in files and os.path.basename(p) not in touched]


def check(names_file, base, absent_file=None):
	names = set(read_list(names_file))
	absent = set(read_list(absent_file)) if absent_file else set()
	allow = set(read_list(os.path.join(VALIDITY, "unclassified.txt")))
	labels = labels_by_test()
	bad = []
	for tsv, f, test, _ in rows():
		if test != "-" and test not in names and test not in absent:
			bad.append("%s: row of %s names ctest '%s', which does not exist" % (tsv, f, test))
	# .gitattributes merges these tables with merge=union: a row both sides edited comes out twice. Same file + test + assertion = one row.
	seen = {}
	for path in sorted(glob.glob(os.path.join(VALIDITY, "*.tsv"))):
		with open(path, encoding="utf-8") as fh:
			for n, line in enumerate(fh, 1):
				key = tuple(line.rstrip("\n").split("\t")[:3])
				if n == 1 or not line.strip():
					continue
				if key in seen:
					bad.append("%s:%d: same file/test/assertion as %s (two versions of one row, e.g. after a union merge: keep one)" % (os.path.basename(path), n, seen[key]))
				else:
					seen[key] = "%s:%d" % (os.path.basename(path), n)
	for test in sorted(names - set(labels) - allow):
		bad.append("ctest '%s' has no rows in cpp/tests/validity/*.tsv (add its rows; do not add it to unclassified.txt)" % test)
	for test in sorted(allow & set(labels)):
		bad.append("'%s' is in unclassified.txt but has rows now: drop it from the list" % test)
	for test in sorted(allow - names):
		bad.append("'%s' is in unclassified.txt but is not a ctest: drop it" % test)
	if base:
		for w in stale_rows_warnings(base):
			print(w)
	for b in sorted(set(bad)):
		print("FAIL:", b)
	print("validity check: %d ctests, %d classified, %d allowlisted unclassified, %d problems" % (len(names), len(labels), len(allow & names), len(set(bad))))
	return 1 if bad else 0


ap = argparse.ArgumentParser()
ap.add_argument("--out")
ap.add_argument("--check", action="store_true")
ap.add_argument("--names")
ap.add_argument("--base")
ap.add_argument("--absent")
a = ap.parse_args()
if a.out:
	write_cmake(a.out)
if a.check:
	if not a.names:
		sys.exit("--check needs --names FILE (one ctest name per line)")
	sys.exit(check(a.names, a.base, a.absent))
