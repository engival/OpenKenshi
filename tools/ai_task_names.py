#!/usr/bin/env python3
"""Generate docs/formats/AI_TASK_ENUMS.md: the taskType value -> name table the client needs for CHAR_STATS row 16.

The names are kinspect's (findings/ai_enum_map.tsv, one row per enum of the original's AI task registry): the enum's own
symbolic name, which is what the spectator view shows. Do not edit the markdown by hand - rerun this script:

    python3 tools/ai_task_names.py                     # ~/git/kenshi/kinspect_bu/ai_enum_map.tsv
    python3 tools/ai_task_names.py --kinspect PATH

The map is game-derived and is not in this repo (docs/LICENSING.md); only the generated table is.
"""
import argparse
import os
import sys

HEADER = """# AI_TASK enum names (taskType values)

The original's AI task enum (`fcs_enums.def`, 291 values: 0-290), one row per value: the enum's symbolic name. CHAR_STATS row 16
sends the value; the client shows the name (SIMLINK.md "CHAR_STATS", the AI tail). Generated by `tools/ai_task_names.py` from
kinspect's `findings/ai_enum_map.tsv` - **do not edit by hand**, rerun the script. The names are the exe's enum names, not the
AI_TASK records' labels.

| value | name | status |
|--:|---|---|
"""


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument('--kinspect', default=os.path.expanduser('~/git/kenshi/kinspect_bu/ai_enum_map.tsv'),
		help='the enum map (default ~/git/kenshi/kinspect_bu/ai_enum_map.tsv)')
	parser.add_argument('--out', default=os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
		'docs', 'formats', 'AI_TASK_ENUMS.md'))
	args = parser.parse_args()

	try:
		with open(args.kinspect, encoding='utf-8') as handle:
			lines = handle.read().splitlines()
	except OSError as error:
		print('ai_task_names: %s' % error, file=sys.stderr)
		return 1
	if not lines or not lines[0].startswith('enum\tname'):
		print('ai_task_names: %s: not the enum map (no enum/name header)' % args.kinspect, file=sys.stderr)
		return 1
	rows = []
	for line in lines[1:]:
		fields = line.split('\t')
		if len(fields) < 3 or not fields[0].isdigit():
			continue
		rows.append((int(fields[0]), fields[1], fields[2]))
	rows.sort()
	if [value for value, _, _ in rows] != list(range(len(rows))):
		print('ai_task_names: the map is not one row per value 0..n-1 (%d rows)' % len(rows), file=sys.stderr)
		return 1

	text = [HEADER]
	for value, name, status in rows:
		text.append('| %d | `%s` | %s |\n' % (value, name, status))
	with open(args.out, 'w', encoding='utf-8') as handle:
		handle.write(''.join(text))
	print('ai_task_names: %d values -> %s' % (len(rows), args.out))
	return 0


if __name__ == '__main__':
	sys.exit(main())
