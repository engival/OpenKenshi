#!/usr/bin/env python3
"""Game-data keys the original exe reads vs keys our code names.

Input: kinspect findings/fcs_coverage.md (dt6), which classifies every (record type, key)
as EXE / FCS-only / DEAD / UNSURE. A key counts as "named by us" when its exact literal
("key") appears in cpp/ or client/ sources (tests, builds and third_party excluded). That
is generous: a key we parse but never use still counts as named.

Usage: tools/data_coverage.py <fcs_coverage.md>  > docs/reference/DATA_COVERAGE.md
"""
import collections
import glob
import re
import sys


def sources():
	files = []
	for pattern in ("cpp/**/*.[ch]pp", "client/**/*.[ch]pp", "client/**/*.[ch]"):
		files += glob.glob(pattern, recursive=True)
	keep = [f for f in files if "/build" not in f and "third_party" not in f and "/tests/" not in f]
	return "".join(open(f, errors="ignore").read() for f in keep)


def rows(path):
	kind = None
	for line in open(path).read().splitlines():
		header = re.match(r"^#{2,4} .*?\b([A-Z][A-Z_0-9]{2,})\b", line)
		if header:
			kind = header.group(1)
		row = re.match(r"^\| `([^`]+)` \| (\w+) \| (\d+) \| (EXE|FCS-only|DEAD|UNSURE) \|", line)
		if row and kind:
			yield kind, row.group(1), int(row.group(3)), row.group(4)


def main():
	src = sources()
	counts = collections.Counter()
	missing = collections.defaultdict(list)
	dead_named = []
	for kind, key, records, cls in rows(sys.argv[1]):
		named = '"%s"' % key in src
		counts[(cls, named)] += 1
		if cls == "EXE" and not named:
			missing[kind].append((records, key))
		if cls == "DEAD" and named:
			dead_named.append((kind, key))
	exe = counts[("EXE", True)] + counts[("EXE", False)]
	print("# Game-data coverage: keys the original reads that we do not\n")
	print("Generated by `tools/data_coverage.py` from kinspect `findings/fcs_coverage.md` (dt6, 8ba7838). Do not edit")
	print("by hand; rerun after a slice that reads new keys. \"Named\" = the key's literal appears in cpp/ or client/")
	print("sources: generous (parsed-but-unused counts as named). Per-key meaning: GAMEDATA_SCHEMA.md and fcs_coverage.md.\n")
	print("Caveats from kinspect: TOWN `roaming squads` is EXE only by name (the traced read is FACTION's);")
	print("SINGLE_DIPLOMATIC_ASSAULT `delivery AI package` / `fallback AI package` have no exe xref: do not build on them.\n")
	print("Rows parsed: %d (kinspect's total is 2,143; rows outside a per-type table are skipped).\n" % sum(counts.values()))
	print("## Totals (type, key rows)\n")
	print("| class | named by us | not named |")
	print("|---|--:|--:|")
	for cls in ("EXE", "FCS-only", "DEAD", "UNSURE"):
		print("| %s | %d | %d |" % (cls, counts[(cls, True)], counts[(cls, False)]))
	print("\nEXE keys named by us: %d of %d (%d%%).\n" % (counts[("EXE", True)], exe, 100 * counts[("EXE", True)] // max(exe, 1)))
	if dead_named:
		print("DEAD keys we still name (drop them): " + ", ".join("%s `%s`" % d for d in dead_named) + "\n")
	print("## EXE keys we do not name, per type (records carrying the key)\n")
	print("| type | n | keys |")
	print("|---|--:|---|")
	for kind, keys in sorted(missing.items(), key=lambda item: -len(item[1])):
		keys.sort(reverse=True)
		print("| %s | %d | %s |" % (kind, len(keys), ", ".join("`%s` %d" % (k, n) for n, k in keys)))


if __name__ == "__main__":
	main()
